"""Mode-aware parameter studies and engineering charts."""

from __future__ import annotations

import streamlit as st

from src.course import ADVANCED_MODE_NOTICE, AppMode
from src.visualizations import (
    MODEL_LABELS,
    compute_parameter_sweep,
    create_ideal_nonideal_chart,
    create_momentum_vector_chart,
    create_parameter_chart,
    dataframe_to_csv_bytes,
    input_snapshot,
    render_brand_bar,
    render_disclaimer,
    render_page_intro,
    render_sidebar_controls,
    simulate_safely,
)

mode = AppMode(st.session_state.get("jf_mode", AppMode.COURSE.value))
course_mode = mode is AppMode.COURSE
inputs, unit_system = render_sidebar_controls()
result = simulate_safely(inputs)
if result is None:
    st.stop()

snapshot = input_snapshot(inputs)
render_brand_bar()
render_page_intro(
    "Sensitivity analysis",
    "Results and Charts",
    "Change one physical input at a time and inspect the signed water-on-plate force components generated by the same momentum solver.",
)
render_disclaimer()

if not course_mode:
    st.info(ADVANCED_MODE_NOTICE, icon=":material/info:")

analysis_view = "Parameter study"
if not course_mode:
    analysis_view = str(
        st.segmented_control(
            "Advanced analysis view",
            options=["Parameter study", "Ideal and non-ideal", "Momentum vectors"],
            default="Parameter study",
            required=True,
            width="stretch",
        )
    )

if analysis_view == "Parameter study":
    variables: list[str] = ["velocity", "diameter"]
    variable_labels = {
        "velocity": "Force versus inlet velocity",
        "diameter": "Force versus jet diameter",
        "beta": "Force versus outlet angle",
        "theta": "Force versus plate tangent angle",
        "retention": "Force versus velocity retention coefficient",
        "split": "Force versus split fraction",
    }
    if not course_mode:
        if snapshot["model"] in {"deflected_jet", "curved_vane"}:
            variables.extend(["beta", "retention"])
        elif snapshot["model"] == "split_flow":
            variables.extend(["theta", "retention", "split"])

    variable = str(
        st.segmented_control(
            "Study variable",
            options=variables,
            format_func=lambda key: variable_labels[key],
            default=variables[0],
            required=True,
            width="stretch",
            help="Course Mode is limited to velocity and diameter studies in SI units.",
        )
    )
    points = st.slider(
        "Study points",
        min_value=21,
        max_value=201 if course_mode else 501,
        value=81,
        step=10,
        help="The deterministic sweep is capped to keep browser interaction responsive.",
    )

    if variable == "velocity":
        start, stop = 0.0, min(50.0 if course_mode else 100.0, max(20.0, inputs.velocity * 1.75))
    elif variable == "diameter":
        start, stop = 0.005, min(0.1 if course_mode else 0.2, max(0.05, inputs.diameter * 2.0))
    elif variable == "beta" or variable == "theta":
        start, stop = -180.0, 180.0
    else:
        start, stop = 0.0, 1.0

    with st.container(horizontal=True, gap="medium"):
        start = st.number_input(
            "Study start",
            value=float(start),
            help="First value of the selected one-parameter study.",
        )
        stop = st.number_input(
            "Study stop",
            value=float(stop),
            help="Last value of the selected one-parameter study.",
        )

    if float(start) >= float(stop):
        st.error("Study stop must be greater than study start.", icon=":material/error:")
        st.stop()

    try:
        frame = compute_parameter_sweep(inputs, variable, float(start), float(stop), int(points))
    except (TypeError, ValueError) as exc:
        st.error(f"The study range is not valid: {exc}", icon=":material/error:")
        st.stop()

    chart = create_parameter_chart(
        frame,
        variable,
        unit_system,
        title=variable_labels[variable],
    )
    st.plotly_chart(
        chart,
        width="stretch",
        config={"displaylogo": False, "responsive": True},
    )
    st.download_button(
        "Download visible study as CSV",
        data=dataframe_to_csv_bytes(
            frame,
            metadata={
                "mode": mode.value,
                "model": MODEL_LABELS[snapshot["model"]],
                "variable": variable,
                "units": unit_system,
            },
        ),
        file_name=f"jetforce_{variable}_study.csv",
        mime="text/csv",
        icon=":material/download:",
        width="stretch",
    )

    if snapshot["model"] == "normal_flat_plate" and variable == "velocity":
        st.success(
            "For the normal flat plate, F = ρAV². The curve is quadratic: doubling V while ρ and d remain fixed multiplies Fx and FR by four.",
            icon=":material/functions:",
        )
    elif snapshot["model"] == "normal_flat_plate" and variable == "diameter":
        st.info(
            "Because A = πd²/4, the ideal normal-impact force also varies with d² when density and velocity remain fixed.",
            icon=":material/functions:",
        )

    with st.expander("View study data", expanded=False):
        st.dataframe(frame, width="stretch", hide_index=True)

elif analysis_view == "Ideal and non-ideal":
    if snapshot["model"] == "normal_flat_plate":
        st.info(
            "The normal-plate net reaction is independent of equal-and-opposite sideways outlet speed in this model. Select a deflected, split, or curved-vane case to inspect k.",
            icon=":material/info:",
        )
    comparison_chart, comparison_frame = create_ideal_nonideal_chart(inputs, unit_system)
    st.plotly_chart(
        comparison_chart,
        width="stretch",
        config={"displaylogo": False, "responsive": True},
    )
    st.dataframe(comparison_frame, width="stretch", hide_index=True)
    st.warning(
        "The selected k value is a user-prescribed outlet-speed assumption. It is not calculated from CFD, experiment, or Reynolds number.",
        icon=":material/warning:",
    )

else:
    st.plotly_chart(
        create_momentum_vector_chart(result, inputs, unit_system),
        width="stretch",
        config={"displaylogo": False, "responsive": True},
    )
    st.caption(
        "The reaction vector equals inlet momentum flux minus the mass-weighted outlet momentum flux. Plot vectors are scaled to keep directions readable."
    )

st.divider()
st.page_link(
    "app_pages/5_Report_and_Export.py",
    label="Continue to Report and Export",
    icon=":material/download:",
    width="stretch",
)
