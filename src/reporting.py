def _leaf_key(key: str) -> str:
    return key.rsplit(".", 1)[-1]


def _label(key: str) -> str:
    leaf = _leaf_key(key)
    return _LABELS.get(leaf, leaf.replace("_", " ").strip().title())


def unit_for_field(key: str) -> str:
    """Return the engineering unit associated with a serialized field name."""

    leaf = _leaf_key(key).lower()
    explicit = {
        "density": "kg/m^3",
        "dynamic_viscosity": "Pa s",
        "diameter": "m",
        "velocity": "m/s",
        "area_m2": "m^2",
        "flow_rate_m3_s": "m^3/s",
        "mass_flow_rate_kg_s": "kg/s",
        "reynolds_number": "dimensionless",
        "re": "dimensionless",
        "retention_coefficient": "dimensionless",
        "split_fraction": "dimensionless",
        "percentage_difference": "%",
    }
    if leaf in explicit:
        return explicit[leaf]
    if leaf.endswith("percentage_difference"):
        return "%"
    suffixes = (
        ("_m3_s", "m^3/s"),
        ("_kg_s", "kg/s"),
        ("_m_s", "m/s"),
        ("_m2", "m^2"),
        ("_deg", "deg"),
        ("_n", "N"),
    )
    for suffix, unit in suffixes:
        if leaf.endswith(suffix):
            return unit
    return ""


def _unit_for_value(key: str, value: Any) -> str:
    """Suppress a nominal unit when a presentation value is not applicable."""

    if value is None or value == "undefined":
        return ""
    unit = unit_for_field(key)
    if unit == "%" and (isinstance(value, bool) or not isinstance(value, (int, float))):
        return ""
    return unit


def _machine_value(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return format(value, ".17g")
    return str(value)


def _display_value(value: Any) -> str:
    if value is None or value == "undefined":
        return "Not applicable"
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if isinstance(value, float):
        if value == 0:
            return "0"
        magnitude = abs(value)
        if magnitude < 1.0e-3 or magnitude >= 1.0e6:
            return f"{value:.6e}"
        return f"{value:.6g}"
    if isinstance(value, (dict, list)):
        return json.dumps(value, ensure_ascii=False, separators=(", ", ": "))
    return str(value)


def export_case_csv(
    inputs: Any,
    result: Any | None = None,
    **report_options: Any,
) -> bytes:
    """Return a long-form UTF-8 CSV for one traceable case."""

    payload = build_report_payload(inputs, result, **report_options)
    stream = io.StringIO(newline="")
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow(("section", "field", "quantity", "value", "unit"))
    sections = (
        ("report", payload["report"]),
        ("inputs", payload["case"]["inputs"]),
        ("results", payload["case"]["results"]),
    )
    for section, values in sections:
        for key, value in _flatten(values):
            writer.writerow(
                (section, key, _label(key), _machine_value(value), _unit_for_value(key, value))
            )
    return stream.getvalue().encode("utf-8")


def export_parametric_csv(table: Any) -> bytes:
    """Return a deterministic wide CSV for a parametric-study table."""

    rows = _records(table, "Parametric data")
    if not rows:
        raise ReportDataError("Parametric export data cannot be empty.")
    columns: list[str] = []
    for row in rows:
        for key in row:
            if key not in columns:
                columns.append(key)
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=columns, lineterminator="\n")
    writer.writeheader()
    for row in rows:
        writer.writerow({key: _machine_value(row.get(key)) for key in columns})
    return stream.getvalue().encode("utf-8")


def export_case_json(
    inputs: Any,
    result: Any | None = None,
    **report_options: Any,
) -> bytes:
    """Return standards-compliant, deterministic UTF-8 JSON for one case."""

    payload = build_report_payload(inputs, result, **report_options)
    try:
        text = json.dumps(
            payload,
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
            allow_nan=False,
        )
    except (TypeError, ValueError) as exc:
        raise ReportDataError(f"The case could not be serialized to JSON: {exc}") from exc
    return (text + "\n").encode("utf-8")


def _table_html(mapping: Mapping[str, Any], caption: str) -> str:
    rows = []
    for key, value in _flatten(mapping):
        rows.append(
            "<tr>"
            f'<th scope="row">{html.escape(_label(key))}</th>'
            f"<td>{html.escape(_display_value(value))}</td>"
            f"<td>{html.escape(_unit_for_value(key, value))}</td>"
            "</tr>"
        )
    return (
        '<div class="table-wrap"><table>'
        f"<caption>{html.escape(caption)}</caption>"
        '<thead><tr><th scope="col">Quantity</th><th scope="col">Value</th>'
        '<th scope="col">Unit</th></tr></thead><tbody>' + "".join(rows) + "</tbody></table></div>"
    )


def _value_from(mapping: Mapping[str, Any], *names: str, default: float = 0.0) -> float:
    for name in names:
        value = mapping.get(name)
        try:
            if value is not None:
                number = float(value)
                return number if math.isfinite(number) else default
        except (TypeError, ValueError):
            continue
    return default


