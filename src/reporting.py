def _figures_html(figures: Sequence[ReportFigure]) -> str:
    if not figures:
        return (
            '<p class="muted">No parametric-study image was supplied for this case export. '
            "Add a verified chart before final submission.</p>"
        )
    blocks = []
    for index, figure in enumerate(figures, 1):
        encoded = base64.b64encode(figure.image_bytes).decode("ascii")
        blocks.append(
            "<figure>"
            f"<h3>{html.escape(figure.title)}</h3>"
            f'<img src="data:{figure.mime_type};base64,{encoded}" '
            f'alt="{html.escape(figure.alt_text)}">'
            f"<figcaption>Figure {index}. {html.escape(figure.caption)}</figcaption>"
            "</figure>"
        )
    return "".join(blocks)


def _record_table_html(records: Sequence[Mapping[str, Any]], limit: int = 40) -> str:
    if not records:
        return '<p class="muted">No parametric-study table was supplied for this case export.</p>'
    columns: list[str] = []
    for row in records:
        for key in row:
            if key not in columns:
                columns.append(key)
    header = "".join(f'<th scope="col">{html.escape(str(key))}</th>' for key in columns)
    body = []
    for row in records[:limit]:
        body.append(
            "<tr>"
            + "".join(f"<td>{html.escape(_display_value(row.get(key)))}</td>" for key in columns)
            + "</tr>"
        )
    note = ""
    if len(records) > limit:
        note = f'<p class="muted">Showing the first {limit} of {len(records)} rows.</p>'
    return (
        '<div class="table-wrap"><table class="compact"><caption>Parametric-study data</caption><thead><tr>'
        + header
        + "</tr></thead><tbody>"
        + "".join(body)
        + "</tbody></table></div>"
        + note
    )


def _optional_mapping_html(value: Any, caption: str, empty_message: str) -> str:
    if not value:
        return f'<p class="muted">{html.escape(empty_message)}</p>'
    if isinstance(value, Mapping):
        return _table_html(value, caption)
    return f"<pre>{html.escape(json.dumps(value, ensure_ascii=False, indent=2))}</pre>"


