def _pdf_records_table(
    records: Sequence[Mapping[str, Any]],
    modules: Mapping[str, Any],
    styles: Mapping[str, Any],
    *,
    limit: int = 30,
) -> Any:
    """Create a compact, genuine tabular view of parameter-sweep records."""

    Paragraph = modules["Paragraph"]
    columns: list[str] = []
    for row in records:
        for key in row:
            if key not in columns:
                columns.append(str(key))
    if not columns:
        raise ReportDataError("Parametric records do not contain any columns.")
    # A portrait A4 report can carry the canonical eight sweep columns at this
    # compact width.  Preserve the swept parameter first and every engineering
    # metric returned by the calculation API.
    available_width = 174 * modules["mm"]
    weight_by_column = []
    for key in columns:
        lowered = key.lower()
        if lowered in {"re", "fx_n", "fy_n", "fr_n"}:
            weight_by_column.append(0.85)
        elif "flow" in lowered or "mdot" in lowered:
            weight_by_column.append(1.1)
        else:
            weight_by_column.append(1.0)
    weight_total = sum(weight_by_column)
    widths = [available_width * weight / weight_total for weight in weight_by_column]

    def header_text(key: str) -> str:
        compact = {
            "Fx_N": "Fx",
            "Fy_N": "Fy",
            "FR_N": "FR",
            "Q_m3_s": "Q",
            "mdot_kg_s": "mdot",
            "Re": "Re",
            "outlet_speed_m_s": "Outlet speed",
        }.get(key, _label(key))
        unit = unit_for_field(key)
        return f"{compact}\n[{unit}]" if unit else compact

    data = [[_pdf_paragraph(header_text(key), styles["CompactHead"], Paragraph) for key in columns]]
    for row in records[:limit]:
        data.append(
            [
                _pdf_paragraph(_display_value(row.get(key)), styles["CompactCell"], Paragraph)
                for key in columns
            ]
        )
    table = modules["Table"](data, colWidths=widths, repeatRows=1)
    table.setStyle(
        modules["TableStyle"](
            [
                ("BACKGROUND", (0, 0), (-1, 0), modules["colors"].HexColor("#0B1F33")),
                ("TEXTCOLOR", (0, 0), (-1, 0), modules["colors"].white),
                (
                    "ROWBACKGROUNDS",
                    (0, 1),
                    (-1, -1),
                    [
                        modules["colors"].white,
                        modules["colors"].HexColor("#F2F7FA"),
                    ],
                ),
                ("GRID", (0, 0), (-1, -1), 0.35, modules["colors"].HexColor("#B7C4D1")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
                ("LEFTPADDING", (0, 0), (-1, -1), 3),
                ("RIGHTPADDING", (0, 0), (-1, -1), 3),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    return table


def _pdf_arrow(
    drawing: Any,
    modules: Mapping[str, Any],
    x1: float,
    y1: float,
    x2: float,
    y2: float,
    color: Any,
    width: float,
) -> None:
    drawing.add(modules["Line"](x1, y1, x2, y2, strokeColor=color, strokeWidth=width))
    angle = math.atan2(y2 - y1, x2 - x1)
    size = 7.0 + width
    left = (x2 - size * math.cos(angle - 0.45), y2 - size * math.sin(angle - 0.45))
    right = (x2 - size * math.cos(angle + 0.45), y2 - size * math.sin(angle + 0.45))
    drawing.add(
        modules["Polygon"](
            [x2, y2, left[0], left[1], right[0], right[1]],
            fillColor=color,
            strokeColor=color,
        )
    )


def _pdf_schematic(payload: Mapping[str, Any], modules: Mapping[str, Any]) -> Any:
    drawing = modules["Drawing"](500, 190)
    colors = modules["colors"]
    navy = colors.HexColor("#172033")
    blue = colors.HexColor("#118AB2")
    red = colors.HexColor("#D1495B")
    gray = colors.HexColor("#72849A")
    case = payload["case"]
    inputs = case["inputs"]
    results = case["results"]
    model = str(inputs.get("model", "normal_flat_plate")).lower()
    impact_x, impact_y = 285.0, 102.0
    drawing.add(
        modules["Rect"](
            205,
            29,
            185,
            150,
            rx=6,
            ry=6,
            fillColor=None,
            strokeColor=gray,
            strokeWidth=1.2,
            strokeDashArray=[5, 4],
        )
    )
    drawing.add(modules["String"](212, 164, "Control volume", fontSize=8, fillColor=gray))
    drawing.add(
        modules["Polygon"](
            [20, 83, 70, 83, 88, 94, 88, 110, 70, 121, 20, 121],
            fillColor=colors.HexColor("#37485C"),
            strokeColor=navy,
        )
    )
    _pdf_arrow(drawing, modules, 88, impact_y, impact_x - 6, impact_y, blue, 5)
    drawing.add(modules["String"](150, 111, "V_in", fontSize=9, fillColor=navy))

    plate_angle, outlet_speed_ratio = _schematic_state(inputs, results, model)
    tangent = math.radians(plate_angle)
    pdx, pdy = 52 * math.cos(tangent), 52 * math.sin(tangent)
    if "curved" in model:
        path = modules["ShapePath"]()
        path.moveTo(impact_x - pdx, impact_y - pdy)
        path.curveTo(
            impact_x + 25,
            impact_y - 20,
            impact_x + 25,
            impact_y + 20,
            impact_x + pdx,
            impact_y + pdy,
        )
        path.strokeColor = navy
        path.strokeWidth = 7
        path.fillColor = None
        drawing.add(path)
    else:
        drawing.add(
            modules["Line"](
                impact_x - pdx,
                impact_y - pdy,
                impact_x + pdx,
                impact_y + pdy,
                strokeColor=navy,
                strokeWidth=7,
            )
        )
    drawing.add(modules["String"](302, 146, "Plate / vane", fontSize=8, fillColor=navy))

    if outlet_speed_ratio <= 1.0e-12:
        drawing.add(modules["String"](300, 126, "V_out = 0", fontSize=8, fillColor=navy))
    elif "split" in model or "normal" in model:
        split_fraction = (
            0.5 if "normal" in model else _value_from(inputs, "split_fraction", default=0.5)
        )
        for index, (angle, fraction) in enumerate(
            zip(
                (plate_angle, plate_angle + 180), (split_fraction, 1 - split_fraction), strict=True
            ),
            1,
        ):
            if fraction <= 1.0e-12:
                continue
            x2, y2 = _rectangle_exit_point(
                impact_x,
                impact_y,
                angle,
                (205.0, 29.0, 390.0, 179.0),
                invert_y=False,
                margin=9.0,
            )
            _pdf_arrow(drawing, modules, impact_x, impact_y, x2, y2, blue, 4)
            label = f"V_out,{index}"
            if "split" in model:
                label += f"; {fraction:.0%} mdot"
            drawing.add(modules["String"](x2 + 4, y2, label, fontSize=8, fillColor=navy))
    else:
        angle = _value_from(inputs, "outlet_angle_deg", default=90.0)
        x2, y2 = _rectangle_exit_point(
            impact_x,
            impact_y,
            angle,
            (205.0, 29.0, 390.0, 179.0),
            invert_y=False,
            margin=9.0,
        )
        _pdf_arrow(drawing, modules, impact_x, impact_y, x2, y2, blue, 4)
        drawing.add(modules["String"](x2 + 4, y2, "V_out", fontSize=8, fillColor=navy))

    fx = _value_from(results, "fx_n")
    fy = _value_from(results, "fy_n")
    force_mag = math.hypot(fx, fy)
    if force_mag > 0:
        x2 = impact_x + 65 * fx / force_mag
        y2 = impact_y + 65 * fy / force_mag
        _pdf_arrow(drawing, modules, impact_x, impact_y, x2, y2, red, 3)
        drawing.add(modules["String"](x2 + 4, y2 - 10, "F_R", fontSize=9, fillColor=red))
    else:
        drawing.add(modules["String"](300, 90, "F_R = 0", fontSize=9, fillColor=red))

    _pdf_arrow(drawing, modules, 40, 30, 92, 30, navy, 1.4)
    _pdf_arrow(drawing, modules, 40, 30, 40, 75, navy, 1.4)
    drawing.add(modules["String"](97, 27, "+x", fontSize=8, fillColor=navy))
    drawing.add(modules["String"](28, 78, "+y", fontSize=8, fillColor=navy))
    drawing.add(
        modules["String"](
            190, 4, "Schematic - not to scale and not CFD", fontSize=8, fillColor=gray
        )
    )
    return drawing


def _pdf_figure(figure: ReportFigure, modules: Mapping[str, Any]) -> Any:
    try:
        reader = modules["ImageReader"](io.BytesIO(figure.image_bytes))
        width, height = reader.getSize()
    except Exception as exc:
        raise ReportDataError(f"Figure '{figure.title}' is not a readable raster image.") from exc
    max_width = 174 * modules["mm"]
    max_height = 108 * modules["mm"]
    scale = min(max_width / width, max_height / height, 1.0)
    return modules["Image"](
        io.BytesIO(figure.image_bytes), width=width * scale, height=height * scale
    )


