def _plain(value: Any) -> Any:
    """Convert supported Python/domain values to deterministic JSON-safe data."""

    if value is None or isinstance(value, (str, bool, int)):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else "undefined"
    if isinstance(value, Enum):
        return _plain(value.value)
    if isinstance(value, (datetime,)):
        return value.isoformat()
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, Mapping):
        return {str(key): _plain(item) for key, item in value.items()}
    if hasattr(value, "item") and callable(value.item):
        try:
            scalar_value = value.item()
        except (TypeError, ValueError):
            scalar_value = value
        if scalar_value is not value:
            return _plain(scalar_value)
    if hasattr(value, "as_dict") and callable(value.as_dict):
        return _plain(value.as_dict())
    if hasattr(value, "to_dict") and callable(value.to_dict):
        try:
            mapping_value = value.to_dict()
        except TypeError:
            mapping_value = value
        if mapping_value is not value:
            return _plain(mapping_value)
    if is_dataclass(value) and not isinstance(value, type):
        return _plain(asdict(value))
    if isinstance(value, (set, frozenset)):
        converted = [_plain(item) for item in value]
        return sorted(
            converted,
            key=lambda item: json.dumps(item, ensure_ascii=True, sort_keys=True, default=str),
        )
    if isinstance(value, (list, tuple)):
        return [_plain(item) for item in value]
    raise ReportDataError(f"Unsupported report value type: {type(value).__name__}.")


def _mapping(value: Any, label: str) -> dict[str, Any]:
    plain = _plain(value)
    if not isinstance(plain, dict):
        raise ReportDataError(f"{label} must be a dataclass, model object, or mapping.")
    return plain


def _records(value: Any, label: str) -> list[dict[str, Any]]:
    """Convert a DataFrame-like object or sequence of mappings to records."""

    if value is None:
        return []
    if hasattr(value, "empty") and bool(value.empty):
        return []
    if hasattr(value, "to_dict") and callable(value.to_dict):
        try:
            candidate = value.to_dict(orient="records")
        except TypeError:
            candidate = value.to_dict()
    else:
        candidate = value
    plain = _plain(candidate)
    if isinstance(plain, dict):
        plain = [plain]
    if not isinstance(plain, list) or not all(isinstance(row, dict) for row in plain):
        raise ReportDataError(f"{label} must be a table or a sequence of row mappings.")
    return plain


def _generated_time(value: datetime | str | None) -> str:
    if value is None:
        value = datetime.now(UTC)
    if isinstance(value, str):
        candidate = value.strip()
        if not candidate:
            raise ReportDataError("Generation time cannot be blank.")
        try:
            value = datetime.fromisoformat(candidate.replace("Z", "+00:00"))
        except ValueError as exc:
            raise ReportDataError("Generation time must be a valid ISO 8601 timestamp.") from exc
    if value.tzinfo is None:
        value = value.replace(tzinfo=UTC)
    return value.astimezone(UTC).isoformat(timespec="seconds")


def build_report_payload(
    inputs: Any,
    result: Any | None = None,
    *,
    metadata: Mapping[str, Any] | None = None,
    assumptions: Sequence[str] | None = None,
    hand_calculation: Any | None = None,
    ideal_comparison: Any | None = None,
    parametric_data: Any | None = None,
    discussion: Sequence[str] | None = None,
    conclusion: str | None = None,
    limitations: Sequence[str] | None = None,
    generated_at: datetime | str | None = None,
) -> dict[str, Any]:
    """Build the canonical report payload without recalculating physics.

    ``inputs`` may be a ``JetInputs`` object, or it may be a simulation result
    when ``result`` is omitted.  The latter form uses ``result.inputs``.
    """

    if result is None and hasattr(inputs, "inputs"):
        result = inputs
        inputs = inputs.inputs
    if result is None:
        raise ReportDataError("A simulation result is required for a case export.")

    input_data = _mapping(inputs, "Inputs")
    result_data = _mapping(result, "Result")
    # SimulationResult.as_dict() intentionally contains input fields for easy
    # flat exports.  Avoid showing those fields twice in the structured report.
    for key in input_data:
        result_data.pop(key, None)
    if not input_data:
        raise ReportDataError("Inputs cannot be empty.")
    if not result_data:
        raise ReportDataError("Results cannot be empty.")
    if result_data.get("force_direction_defined") is False:
        result_data["force_angle_deg"] = "undefined"

    generated_timestamp = _generated_time(generated_at)
    report_meta: dict[str, Any] = {
        "title": DEFAULT_REPORT_TITLE,
        "subtitle": DEFAULT_REPORT_SUBTITLE,
        "course": DEFAULT_COURSE,
        "disclaimer": DISCLAIMER,
        "review_note": REVIEW_NOTE,
    }
    if metadata is not None:
        report_meta.update(_mapping(metadata, "Metadata"))
    # These reserved fields describe the code/model that generated the report.
    # Apply them after user metadata so a caller cannot accidentally spoof them.
    report_meta.update(
        {
            "application_version": application_version(),
            "model_revision": MODEL_REVISION,
            "build_commit": build_commit(),
            "generated_at": generated_timestamp,
        }
    )

    if report_meta.get("interface_mode") == "Course Mode":
        course_input_fields = {
            "density",
            "diameter",
            "velocity",
            "model",
            "fluid_preset",
            "unit_system",
        }
        if input_data.get("model") != "normal_flat_plate":
            course_input_fields.add("outlet_angle_deg")
        input_data = {key: value for key, value in input_data.items() if key in course_input_fields}
        course_result_fields = {
            "area_m2",
            "flow_rate_m3_s",
            "mass_flow_rate_kg_s",
            "inlet_velocity_x_m_s",
            "inlet_velocity_y_m_s",
            "equivalent_outlet_velocity_x_m_s",
            "equivalent_outlet_velocity_y_m_s",
            "outlet_momentum_flux_x_n",
            "outlet_momentum_flux_y_n",
            "fx_n",
            "fy_n",
            "resultant_force_n",
            "force_angle_deg",
            "force_direction_defined",
        }
        result_data = {
            key: value for key, value in result_data.items() if key in course_result_fields
        }

    selected_assumptions = list(DEFAULT_ASSUMPTIONS if assumptions is None else assumptions)
    selected_discussion = list(DEFAULT_DISCUSSION if discussion is None else discussion)
    selected_limitations = list(DEFAULT_LIMITATIONS if limitations is None else limitations)
    if not all(isinstance(item, str) and item.strip() for item in selected_assumptions):
        raise ReportDataError("Every assumption must be non-empty text.")
    if not all(isinstance(item, str) and item.strip() for item in selected_discussion):
        raise ReportDataError("Every discussion point must be non-empty text.")
    if not all(isinstance(item, str) and item.strip() for item in selected_limitations):
        raise ReportDataError("Every limitation must be non-empty text.")

    selected_equations = list(GOVERNING_EQUATIONS)
    if report_meta.get("interface_mode") == "Course Mode":
        selected_equations = [
            equation for equation in selected_equations if not equation.startswith("Re =")
        ]

    payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "report": _plain(report_meta),
        "case": {"inputs": input_data, "results": result_data},
        "assumptions": selected_assumptions,
        "governing_equations": selected_equations,
        "calculation_procedure": [
            "Calculate circular jet area from the specified diameter.",
            "Calculate volumetric and mass flow rates from the inlet speed.",
            "Construct the model-specific outlet velocity vector or vectors.",
            "Sum outlet momentum fluxes and subtract them from inlet momentum flux.",
            "Report fluid-on-plate force components, resultant, and direction.",
        ],
        "hand_calculation": ({} if hand_calculation is None else _plain(hand_calculation)),
        "ideal_comparison": ({} if ideal_comparison is None else _plain(ideal_comparison)),
        "parametric_study": _records(parametric_data, "Parametric data"),
        "discussion": selected_discussion,
        "conclusion": conclusion
        or (
            "The selected case was evaluated with the documented steady control-volume "
            "momentum model. Review the component directions, analytical checks, and "
            "parameter trends before drawing a case-specific engineering conclusion."
        ),
        "limitations": selected_limitations,
        "references": (
            "Placeholder - add only authoritative references personally checked by the student."
        ),
    }
    return cast(dict[str, Any], _plain(payload))


def _flatten(mapping: Mapping[str, Any], prefix: str = "") -> list[tuple[str, Any]]:
    rows: list[tuple[str, Any]] = []
    for key, value in mapping.items():
        name = f"{prefix}.{key}" if prefix else str(key)
        if isinstance(value, Mapping):
            rows.extend(_flatten(value, name))
        elif isinstance(value, list):
            rows.append((name, json.dumps(value, ensure_ascii=False, separators=(",", ":"))))
        else:
            rows.append((name, value))
    return rows


