class ReportError(RuntimeError):
    """Base class for readable report/export failures."""


class ReportDataError(ReportError, ValueError):
    """Raised when an export request contains no usable or unsupported data."""


class ReportDependencyError(ReportError):
    """Raised when an optional report dependency is unavailable."""


