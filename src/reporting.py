@dataclass(frozen=True, slots=True)
class ReportFigure:
    """One verified raster image for a printable engineering report.

    ``image_bytes`` must contain PNG or JPEG data.  A caption is required so a
    figure remains understandable outside the live application.
    """

    title: str
    image_bytes: bytes
    caption: str
    alt_text: str = "Engineering result figure"
    mime_type: str = "image/png"

    def __post_init__(self) -> None:
        if not self.title.strip():
            raise ReportDataError("A report figure requires a non-empty title.")
        if not self.caption.strip():
            raise ReportDataError("A report figure requires a non-empty caption.")
        if not self.image_bytes:
            raise ReportDataError("A report figure cannot contain empty image data.")
        if self.mime_type not in {"image/png", "image/jpeg"}:
            raise ReportDataError("Report figures must be PNG or JPEG images.")


