def safe_export_filename(
    stem: str = "jetforce_case",
    extension: str = "json",
    *,
    generated_at: datetime | None = None,
) -> str:
    """Return a path-free export filename with a sortable UTC timestamp."""

    clean_stem = re.sub(r"[^A-Za-z0-9_-]+", "_", stem.strip()).strip("_-")
    clean_extension = re.sub(r"[^A-Za-z0-9]+", "", extension.lstrip("."))
    if not clean_stem:
        clean_stem = "jetforce_case"
    if not clean_extension:
        raise ReportDataError("Export extension must contain letters or numbers.")
    instant = generated_at or datetime.now(UTC)
    if instant.tzinfo is None:
        instant = instant.replace(tzinfo=UTC)
    stamp = instant.astimezone(UTC).strftime("%Y%m%dT%H%M%SZ")
    return f"{clean_stem}_{stamp}.{clean_extension.lower()}"


def write_export_file(data: bytes | str, destination: str | Path) -> Path:
    """Atomically write one generated export to an existing directory."""

    target = Path(destination).expanduser()
    if not target.name:
        raise ReportWriteError("An export filename is required.")
    if not target.parent.exists():
        raise ReportWriteError(f"Export directory does not exist: {target.parent}")
    payload = data.encode("utf-8") if isinstance(data, str) else data
    if not payload:
        raise ReportDataError("Generated export data cannot be empty.")
    temporary_name: str | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="wb", prefix=f".{target.name}.", suffix=".tmp", dir=target.parent, delete=False
        ) as stream:
            temporary_name = stream.name
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary_name, target)
    except OSError as exc:
        if temporary_name is not None:
            with contextlib.suppress(OSError):
                Path(temporary_name).unlink(missing_ok=True)
        raise ReportWriteError(f"Could not write export file '{target}': {exc}") from exc
    return target


